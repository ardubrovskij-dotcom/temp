"""Названия дней недели для чата."""

from datetime import date

# Индекс совпадает с date.weekday(): 0 = понедельник.
REAL_NAMES = [
    "понедельник",
    "вторник",
    "среда",
    "четверг",
    "пятница",
    "суббота",
    "воскресенье",
]

CHAT_NAMES = [
    "Дрочельник",
    "Фуррник",
    "Квадра",
    "Хоббихорсинг",
    "Нефорятница",
    "Гномбота",
    "Цуцикенье",
]

# Форма для фразы «поздравляю всех с …» (творительный падеж).
CHAT_NAMES_INSTR = [
    "Дрочельником",
    "Фуррником",
    "Квадрой",
    "Хоббихорсингом",
    "Нефорятницей",
    "Гномботой",
    "Цуцикеньем",
]


def greeting(day: date) -> str:
    i = day.weekday()
    return f"Сегодня {REAL_NAMES[i]} — поздравляю всех с {CHAT_NAMES_INSTR[i]}!"
